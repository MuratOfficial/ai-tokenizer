// Сценарии «запрос → ответ» с ветвлением.
// Каждый узел — один шаг выбора следующего токена: кандидаты, их вероятности и причины.
// Вероятности и причины написаны вручную для наглядности: настоящая модель считает их нейросетью.

export const END = "<конец>";

export type Option = {
  /** Текст токена */
  t: string;
  /** Вероятность в % (сумма по узлу меньше 100 — остаток уходит «всем остальным токенам») */
  p: number;
  /** Следующий узел; null — ответ закончен */
  to: string | null;
  /** Почему у токена такая вероятность */
  why: string;
};

export type GenNode = {
  /** Что происходит на этом шаге */
  note: string;
  /** Индексы токенов запроса, на которые модель опирается сильнее всего */
  focus?: number[];
  options: Option[];
};

export type Scenario = {
  label: string;
  about: string;
  prompt: string[];
  start: string;
  nodes: Record<string, GenNode>;
};

const o = (t: string, p: number, to: string | null, why: string): Option => ({ t, p, to, why });

