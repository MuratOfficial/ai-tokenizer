/** Условный номер токена: у настоящих моделей он берётся из словаря */
export function fakeId(text: string) {
  let h = 7;
  for (const ch of text) h = (h * 31 + ch.codePointAt(0)!) % 50000;
  return h;
}

/** Сколько «остальных» токенов условно делят между собой остаток вероятности */
const REST_TOKENS = 30;

/**
 * Пересчёт вероятностей с учётом температуры.
 * T = 0 — всегда самый вероятный; T = 1 — как есть; T > 1 — шансы выравниваются.
 */
export function withTemperature(options: Option[], temp: number) {
  const rest = Math.max(0, 100 - options.reduce((s, x) => s + x.p, 0));
  if (temp === 0) {
    const best = options.reduce((m, x, i) => (x.p > options[m].p ? i : m), 0);
    return { probs: options.map((_, i) => (i === best ? 100 : 0)), rest: 0 };
  }
  const w = options.map((x) => Math.pow(x.p / 100, 1 / temp));
  const restW = rest ? REST_TOKENS * Math.pow(rest / 100 / REST_TOKENS, 1 / temp) : 0;
  const total = w.reduce((s, x) => s + x, 0) + restW;
  return { probs: w.map((x) => (x / total) * 100), rest: (restW / total) * 100 };
}
