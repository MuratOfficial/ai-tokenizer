export type CorpusGroup = {
  /** Варианты вопроса. Пустой список у группы с after — «подходит любой ответ» */
  q: string[];
  /** Варианты ответа. Могут содержать {name}, {reply}, {last} — подставляются из памяти */
  a: string[];
  /** Какой встречный вопрос задать после ответа (ключ из follows) */
  follow?: string;
  /** Группа работает, только если модель перед этим задала вопрос с таким тегом */
  after?: string;
  /** Группа работает, только пока модель этого НЕ помнит */
  lacks?: "name" | "last";
  /** newName — только если имя названо в этом сообщении; oldName — только если имя уже было в памяти */
  when?: "newName" | "oldName";
};

